-- ---------- Administradores ----------
-- Quem está nesta tabela pode adicionar, editar e excluir roteiros.
-- Todos os outros usuários com login só leem e baixam.
create table if not exists public.admins (
  user_id   uuid primary key references auth.users(id) on delete cascade,
  criado_em timestamptz not null default now()
);
alter table public.admins enable row level security;

drop policy if exists "admins: cada um ve o proprio registro" on public.admins;
create policy "admins: cada um ve o proprio registro"
  on public.admins for select to authenticated
  using (user_id = auth.uid());

create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

-- ---------- Roteiros ----------
create table if not exists public.roteiros (
  id            uuid primary key default gen_random_uuid(),
  numero        bigint generated by default as identity unique,
  titulo        text not null check (char_length(titulo) between 1 and 140),
  passagem      text not null default '',
  tags          text[] not null default '{}',
  resumo        text not null default '',
  roteiro       text not null default '',
  pdf_path      text,
  pdf_nome      text,
  pdf_tamanho   bigint,
  pdf_paginas   int,
  texto_pdf     text not null default '',
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
alter table public.roteiros enable row level security;

drop policy if exists "roteiros: leitura para quem entrou" on public.roteiros;
create policy "roteiros: leitura para quem entrou"
  on public.roteiros for select to authenticated using (true);

drop policy if exists "roteiros: admins criam" on public.roteiros;
create policy "roteiros: admins criam"
  on public.roteiros for insert to authenticated with check (public.is_admin());

drop policy if exists "roteiros: admins editam" on public.roteiros;
create policy "roteiros: admins editam"
  on public.roteiros for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

drop policy if exists "roteiros: admins excluem" on public.roteiros;
create policy "roteiros: admins excluem"
  on public.roteiros for delete to authenticated using (public.is_admin());

-- ---------- PDFs (Storage) ----------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('roteiros-pdf', 'roteiros-pdf', false, 20971520, array['application/pdf'])
on conflict (id) do nothing;

drop policy if exists "pdf: leitura para quem entrou" on storage.objects;
create policy "pdf: leitura para quem entrou"
  on storage.objects for select to authenticated
  using (bucket_id = 'roteiros-pdf');

drop policy if exists "pdf: admins enviam" on storage.objects;
create policy "pdf: admins enviam"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'roteiros-pdf' and public.is_admin());

drop policy if exists "pdf: admins atualizam" on storage.objects;
create policy "pdf: admins atualizam"
  on storage.objects for update to authenticated
  using (bucket_id = 'roteiros-pdf' and public.is_admin());

drop policy if exists "pdf: admins excluem" on storage.objects;
create policy "pdf: admins excluem"
  on storage.objects for delete to authenticated
  using (bucket_id = 'roteiros-pdf' and public.is_admin());

